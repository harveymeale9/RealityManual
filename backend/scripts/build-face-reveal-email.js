// Keep the email HTML as a readable source while shipping a Worker-safe JS
// string. Cloudflare Workers cannot read the backend filesystem at runtime.
const fs = require('node:fs');
const path = require('node:path');

const source = path.join(__dirname, '../src/services/faceRevealEmail.html');
const target = path.join(__dirname, '../src/services/faceRevealEmail.generated.js');
const html = fs.readFileSync(source, 'utf8');
fs.writeFileSync(target, `// Generated by backend/scripts/build-face-reveal-email.js; edit faceRevealEmail.html instead.\nmodule.exports = ${JSON.stringify(html)};\n`);
