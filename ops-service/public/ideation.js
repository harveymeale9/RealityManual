(function () {
  'use strict';

  var root = null;
  var timer = null;
  var lastHash = '';
  var activeDictationStop = null;

  function esc(value) {
    return String(value == null ? '' : value).replace(/[&<>"']/g, function (char) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char];
    });
  }

  function api(path, options) {
    options = options || {};
    options.credentials = 'include';
    options.headers = Object.assign({ 'Content-Type': 'application/json' }, options.headers || {});
    return fetch('/api/ideation' + path, options).then(function (response) {
      return response.json().then(function (data) {
        if (!response.ok) throw new Error(data.error || 'Request failed');
        return data;
      });
    });
  }

  function quoteMarkup(quotes) {
    if (!quotes || !quotes.length) return '<p class="idea-none">No verified quotes supplied.</p>';
    return quotes.map(function (quote) {
      return '<blockquote><p>“' + esc(quote.text) + '”</p><cite>Page ' + esc(quote.page) + '</cite></blockquote>';
    }).join('');
  }

  function feedbackMarkup(entries) {
    if (!entries || !entries.length) return '<p class="idea-none">No direct feedback yet.</p>';
    return entries.map(function (entry) {
      return '<div class="idea-feedback-entry"><span>' + esc(entry.source) + ' · ' + new Date(entry.created_at).toLocaleString() + '</span>' + esc(entry.text) + '</div>';
    }).join('');
  }

  function card(idea, index) {
    var meta = idea.generation_meta || {};
    return '<article class="idea-card idea-big-card' + (idea.edited ? ' is-edited' : '') + '" data-idea="' + esc(idea.id) + '">' +
      '<header class="idea-big-head"><span class="idea-number">' + String(index + 1).padStart(2, '0') + '</span><span>Big Idea</span><span class="idea-origin">' + esc(idea.provider) + '</span></header>' +
      '<div class="idea-big-body"><div class="idea-big-edit"><label for="idea-text-' + esc(idea.id) + '">Big Idea text</label><textarea class="idea-big-editor" id="idea-text-' + esc(idea.id) + '" rows="3">' + esc(idea.big_idea) + '</textarea>' +
      '<div class="idea-big-edit-actions"><button type="button" class="idea-save" disabled>Save changes</button><button type="button" class="idea-mic idea-dictate" aria-label="Dictate changes" title="Dictate changes"><svg viewBox="0 0 24 24" aria-hidden="true"><rect x="8" y="3" width="8" height="12" rx="4"/><path d="M5 11a7 7 0 0 0 14 0M12 18v3M9 21h6"/></svg><span>Dictate</span></button><span class="idea-edit-status" role="status" aria-live="polite"></span></div></div>' +
      '<div class="idea-big-support"><section><h3>Concepts / angles to mention</h3><ul>' +
        (idea.discussion_angles || []).map(function (angle) { return '<li>' + esc(angle) + '</li>'; }).join('') +
      '</ul></section><section class="idea-big-quotes"><h3>Direct quotes</h3>' + quoteMarkup(idea.verified_quotes) + '</section></div>' +
      '<section class="idea-feedback"><div class="idea-section-head"><h3>Direct feedback</h3><span>Strong learning signal for future Big Ideas</span></div><div class="idea-feedback-history">' + feedbackMarkup(idea.feedback) + '</div><div class="idea-feedback-compose"><textarea class="idea-feedback-input" rows="2" placeholder="Tell the generator exactly what works, what doesn’t, or what it should learn from this idea…"></textarea><button class="idea-mic idea-feedback-dictate" type="button" title="Dictate feedback" aria-label="Dictate feedback"><svg viewBox="0 0 24 24" aria-hidden="true"><rect x="8" y="3" width="8" height="12" rx="4"/><path d="M5 11a7 7 0 0 0 14 0M12 18v3M9 21h6"/></svg><span>Dictate</span></button><button class="idea-feedback-save" type="button" disabled>Teach generator</button></div><span class="idea-feedback-status" role="status" aria-live="polite"></span></section>' +
      '<footer class="idea-big-footer"><button class="idea-send" type="button">Send to Rough Ideas</button><button class="idea-reject" type="button">Not interested</button>' +
      '<span class="idea-status" role="status" aria-live="polite"></span>' +
      '<span class="idea-meta">Generated by ' + esc(idea.provider) + ' · ' + esc(idea.model) + (meta.generatedAt ? ' · ' + new Date(meta.generatedAt).toLocaleString() : '') + '</span></footer></div></article>';
  }

  function jobs(state) {
    var missing = Math.max(0, state.target - state.ideas.length);
    var open = (state.jobs || []).filter(function (job) { return job.kind === 'generate' && job.status !== 'error'; });
    var html = '';
    for (var i = 0; i < missing; i++) {
      html += '<div class="idea-card idea-generating"><div class="idea-pulse"></div><div><strong>Generating a grounded Big Idea…</strong><span>' + esc(open[0] ? open[0].provider : state.selectedProvider) + ' is reading the manuscript and checking for duplicates.</span></div></div>';
    }
    (state.jobs || []).filter(function (job) { return job.status === 'error'; }).forEach(function (job) {
      html += '<div class="idea-job-error"><strong>' + esc(job.provider) + ' generation failed</strong><span>' + esc(job.error) + '</span><button data-retry="' + esc(job.id) + '">Retry with ' + esc(job.provider) + '</button></div>';
    });
    return html;
  }

  function setStatus(cardEl, text, bad) {
    var status = cardEl.querySelector('.idea-status');
    status.textContent = text;
    status.classList.toggle('bad', !!bad);
  }

  function resizeEditor(editor) {
    editor.style.height = 'auto';
    editor.style.height = Math.max(92, editor.scrollHeight) + 'px';
  }

  function insertDictation(editor, before, spoken, after) {
    var leftSpace = before && !/\s$/.test(before) ? ' ' : '';
    var rightSpace = after && !/^\s/.test(after) ? ' ' : '';
    editor.value = before + leftSpace + spoken.trim() + rightSpace + after;
    editor.dataset.voice = 'true';
    editor.dispatchEvent(new Event('input', { bubbles: true }));
  }

  function startDictation(cardEl, editor, button) {
    if (activeDictationStop) { activeDictationStop(); return; }
    var Voice = window.RMVoice;
    var SpeechRecognitionCtor = window.SpeechRecognition || window.webkitSpeechRecognition;
    var start = editor.selectionStart == null ? editor.value.length : editor.selectionStart;
    var end = editor.selectionEnd == null ? start : editor.selectionEnd;
    var before = editor.value.slice(0, start);
    var after = editor.value.slice(end);
    var label = button.querySelector('span');
    var actionRow = button.parentElement;
    var status = actionRow && actionRow.parentElement ? actionRow.parentElement.querySelector('.idea-edit-status, .idea-feedback-status') : null;
    status = status || cardEl.querySelector('.idea-edit-status');

    function recording(on) {
      button.classList.toggle('recording', on);
      label.textContent = on ? 'Stop' : 'Dictate';
      button.title = on ? 'Stop dictation' : 'Dictate changes';
      button.setAttribute('aria-label', button.title);
      status.textContent = on ? 'Listening… click Stop when finished.' : '';
    }

    if (SpeechRecognitionCtor) {
      var recognition = new SpeechRecognitionCtor();
      var finalTranscript = '';
      recognition.continuous = true;
      recognition.interimResults = true;
      recognition.addEventListener('result', function (event) {
        var interim = '';
        for (var i = event.resultIndex; i < event.results.length; i++) {
          var chunk = event.results[i][0].transcript;
          if (event.results[i].isFinal) finalTranscript += chunk + ' ';
          else interim += chunk;
        }
        insertDictation(editor, before, finalTranscript + interim, after);
      });
      recognition.addEventListener('end', function () {
        activeDictationStop = null;
        recording(false);
        status.textContent = editor.value.trim() ? 'Dictation added — review and save.' : '';
      });
      recognition.addEventListener('error', function (event) {
        activeDictationStop = null;
        recording(false);
        if (event.error !== 'aborted' && event.error !== 'no-speech') status.textContent = 'Microphone error: ' + event.error;
      });
      activeDictationStop = function () { recognition.stop(); };
      recording(true);
      recognition.start();
      return;
    }

    if (!Voice) { status.textContent = 'Voice dictation is unavailable in this browser.'; return; }
    Voice.startRecording().then(function (recorder) {
      recording(true);
      activeDictationStop = function () {
        activeDictationStop = null;
        recording(false);
        button.disabled = true;
        status.textContent = 'Transcribing…';
        recorder.stop().then(Voice.transcribe).then(function (text) {
          if (text) insertDictation(editor, before, text, after);
          status.textContent = text ? 'Dictation added — review and save.' : 'No speech detected.';
        }).catch(function (error) {
          status.textContent = error.message || 'Could not transcribe audio.';
        }).finally(function () { button.disabled = false; });
      };
    }).catch(function () { status.textContent = 'Could not access the microphone. Check its permission.'; });
  }

  function bind(state) {
    root.querySelectorAll('[data-provider]').forEach(function (button) {
      button.onclick = function () {
        api('/provider', { method: 'PUT', body: JSON.stringify({ provider: button.dataset.provider }) })
          .then(function () { lastHash = ''; refresh(); });
      };
    });

    root.querySelectorAll('.idea-card[data-idea]').forEach(function (cardEl) {
      var editor = cardEl.querySelector('.idea-big-editor');
      var save = cardEl.querySelector('.idea-save');
      var dictate = cardEl.querySelector('.idea-dictate');
      var editStatus = cardEl.querySelector('.idea-edit-status');
      var feedbackBox = cardEl.querySelector('.idea-feedback-input');
      var feedbackSave = cardEl.querySelector('.idea-feedback-save');
      var feedbackDictate = cardEl.querySelector('.idea-feedback-dictate');
      var feedbackStatus = cardEl.querySelector('.idea-feedback-status');
      var savedValue = editor.value;
      resizeEditor(editor);
      editor.addEventListener('input', function () {
        resizeEditor(editor);
        var dirty = editor.value !== savedValue;
        save.disabled = !dirty || editor.value.trim().length < 20;
        editStatus.textContent = dirty ? 'Unsaved changes' : '';
      });
      dictate.onclick = function () { startDictation(cardEl, editor, dictate); };
      feedbackBox.addEventListener('input', function () {
        feedbackSave.disabled = feedbackBox.value.trim().length < 2;
        feedbackStatus.textContent = feedbackBox.value.trim() ? 'Unsaved feedback' : '';
      });
      feedbackDictate.onclick = function () { startDictation(cardEl, feedbackBox, feedbackDictate); };
      feedbackSave.onclick = function () {
        var text = feedbackBox.value.trim();
        if (!text) return;
        feedbackSave.disabled = true;
        feedbackDictate.disabled = true;
        feedbackStatus.textContent = 'Teaching the generator…';
        api('/ideas/' + cardEl.dataset.idea + '/feedback', { method: 'POST', body: JSON.stringify({ text: text, source: feedbackBox.dataset.voice === 'true' ? 'voice' : 'typed' }) }).then(function () {
          feedbackStatus.textContent = 'Feedback saved and learning queued';
          lastHash = '';
          refresh();
        }).catch(function (error) {
          feedbackSave.disabled = false;
          feedbackStatus.textContent = error.message;
        }).finally(function () { feedbackDictate.disabled = false; });
      };
      save.onclick = function () {
        save.disabled = true;
        dictate.disabled = true;
        editStatus.textContent = 'Saving…';
        api('/ideas/' + cardEl.dataset.idea, { method: 'PUT', body: JSON.stringify({ bigIdea: editor.value }) }).then(function (result) {
          savedValue = result.idea.big_idea;
          editor.value = savedValue;
          resizeEditor(editor);
          cardEl.classList.add('is-edited');
          editStatus.textContent = 'Saved';
          lastHash = '';
        }).catch(function (error) {
          save.disabled = false;
          editStatus.textContent = error.message;
        }).finally(function () { dictate.disabled = false; });
      };
      cardEl.querySelector('.idea-send').onclick = function (event) {
        var button = event.currentTarget;
        button.disabled = true;
        setStatus(cardEl, 'Sending to Rough Ideas…');
        api('/ideas/' + cardEl.dataset.idea + '/transfer', { method: 'POST', body: '{}' }).then(function () {
          cardEl.classList.add('idea-exit-send');
          setTimeout(function () { lastHash = ''; refresh(); }, 360);
        }).catch(function (error) {
          button.disabled = false;
          setStatus(cardEl, error.message, true);
        });
      };
      cardEl.querySelector('.idea-reject').onclick = function (event) {
        var button = event.currentTarget;
        button.disabled = true;
        setStatus(cardEl, 'Teaching the generator from this rejection…');
        api('/ideas/' + cardEl.dataset.idea + '/reject', { method: 'POST', body: '{}' }).then(function () {
          cardEl.classList.add('idea-exit-reject');
          setTimeout(function () { lastHash = ''; refresh(); }, 360);
        }).catch(function (error) {
          button.disabled = false;
          setStatus(cardEl, error.message, true);
        });
      };
    });

    root.querySelectorAll('[data-retry]').forEach(function (button) {
      button.onclick = function () {
        button.disabled = true;
        api('/jobs/' + button.dataset.retry + '/retry', { method: 'POST', body: '{}' })
          .then(function () { lastHash = ''; refresh(); })
          .catch(function () { button.disabled = false; });
      };
    });
  }

  function render(state) {
    if (!root || location.hash !== '#content-ideation') return;
    var hash = JSON.stringify(state);
    if (hash === lastHash) return;
    lastHash = hash;
    root.innerHTML = '<div class="ideation-workspace"><header class="ideation-hero"><div><div class="eyebrow">Manuscript-grounded Big Ideas</div><h2>Content Ideation</h2><p>Practical, distinctive premises from the book—no titles, hooks, scripts, outlines, or production instructions.</p></div>' +
      '<div class="idea-provider"><span>Generation model</span><div role="group"><button data-provider="codex" class="' + (state.selectedProvider === 'codex' ? 'active' : '') + '">Codex</button><button data-provider="claude" class="' + (state.selectedProvider === 'claude' ? 'active' : '') + '">Claude</button></div><small>Applies to the next Big Ideas generated.</small></div></header>' +
      '<div class="idea-queue-bar"><span><b>' + state.ideas.length + '</b> / ' + state.target + ' Big Ideas</span><span>Choose one to develop yourself in the Content Pipeline</span></div>' +
      '<div class="idea-list">' + state.ideas.map(card).join('') + jobs(state) + '</div></div>';
    bind(state);
  }

  function refresh() {
    api('/state').then(render).catch(function (error) {
      if (root) root.innerHTML = '<div class="idea-fatal">Could not load Content Ideation: ' + esc(error.message) + '</div>';
    });
  }

  function mount(container) {
    root = container;
    lastHash = '';
    if (timer) clearInterval(timer);
    root.innerHTML = '<div class="idea-loading" role="status" aria-label="Loading Content Ideation"><span aria-hidden="true"></span></div>';
    refresh();
    timer = setInterval(function () {
      if (location.hash === '#content-ideation') refresh();
      else { clearInterval(timer); timer = null; }
    }, 5000);
  }

  window.RMIdeation = { mount: mount };
})();
